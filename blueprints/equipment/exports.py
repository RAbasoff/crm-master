@bp.route('/equipment/report')
@login_required
@role_required('admin', 'director', 'technician')
def equipment_report():
    """Печатный отчёт по записям MRO (все или выбранные ?ids=1,2,3)."""
    records = _equipment_ids_query(request.args.get('ids', '')).order_by(
        EquipmentMaintenance.date.desc(), EquipmentMaintenance.id.desc()).all()
    return render_template('equipment_report.html', records=records,
                           generated_at=datetime.now())


@bp.route('/equipment/export/pdf')
@login_required
@role_required('admin', 'director', 'technician')
def equipment_export_pdf():
    """PDF-экспорт записей MRO (все или выбранные ?ids=1,2,3)."""
    records = _equipment_ids_query(request.args.get('ids', '')).order_by(
        EquipmentMaintenance.date.desc(), EquipmentMaintenance.id.desc()).all()
    try:
        fpdf_mod = ensure_fpdf()
        FPDF = fpdf_mod.FPDF
    except Exception as e:
        msg = f'{e} | python={_sys.executable} | path0={(_sys.path[0] if _sys.path else "")}'
        print(f'equipment_export_pdf: fpdf unavailable: {msg}')
        log_system('error', 'export', f'PDF export failed: fpdf unavailable: {msg}')
        flash(_('PDF export is temporarily unavailable') + f' — {e}', 'error')
        return redirect(url_for('equipment.equipment_list'))
    date_str = datetime.now().strftime('%d-%m-%Y %H:%M')
    title = _('Mule Maintenance Report')
    footer_txt = _('Generated by ProMaster CRM')
    page_txt = _('page')

    font_path = find_pdf_font()
    font_ok = {'unicode': bool(font_path)}
    print(f'equipment_export_pdf: font={font_path!r} records={len(records)}')

    def pdf_text(s):
        s = str(s if s is not None else '')
        if font_ok['unicode']:
            return s
        return s.encode('latin-1', 'replace').decode('latin-1')

    # Probe TTF embedding — stub fontTools cannot add_font
    if font_ok['unicode']:
        try:
            _probe = FPDF()
            _probe.add_font('AppFont', '', font_path)
        except Exception as _font_err:
            print(f'MRO PDF: add_font failed ({_font_err}), fallback Helvetica')
            font_ok['unicode'] = False

    try:
        return _build_mro_pdf(records, FPDF, font_ok['unicode'], font_path, pdf_text,
                              title, date_str, footer_txt, page_txt)
    except Exception as e:
        tb = traceback.format_exc()
        print(f'equipment_export_pdf FAILED: {e}\n{tb}')
        log_system('error', 'export', f'MRO PDF export failed: {e}')
        flash(_('PDF export failed: %(err)s', err=str(e)), 'error')
        return redirect(url_for('equipment.equipment_list'))


def _build_mro_pdf(records, FPDF, unicode_font, font_path, pdf_text,
                   title, date_str, footer_txt, page_txt):
    class MroPDF(FPDF):
        def header(self):
            fn = 'AppFont' if unicode_font else 'Helvetica'
            self.set_font(fn, 'B', 12)
            self.cell(0, 8, pdf_text(f'{title} - ProMaster'), new_x='LMARGIN', new_y='NEXT')
            self.set_font(fn, '', 8)
            self.cell(0, 5, pdf_text(f'{date_str} - {len(records)} {_("records")}'),
                      new_x='LMARGIN', new_y='NEXT')
            self.ln(2)

        def footer(self):
            fn = 'AppFont' if unicode_font else 'Helvetica'
            self.set_y(-12)
            self.set_font(fn, '', 7)
            self.set_text_color(128)
            self.cell(0, 8, pdf_text(f'{footer_txt} - {page_txt} {self.page_no()}/{{nb}}'), align='C')

    pdf = MroPDF(orientation='P', unit='mm', format='A4')
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=15)
    if unicode_font:
        try:
            pdf.add_font('AppFont', '', font_path)
            pdf.add_font('AppFont', 'B', font_path)
            base_font = 'AppFont'
        except Exception:
            unicode_font = False
            base_font = 'Helvetica'
    else:
        base_font = 'Helvetica'
    pdf.add_page()

    def field_row(label, value, bold=False):
        if not value:
            return
        fn = 'AppFont' if unicode_font else 'Helvetica'
        pdf.set_font(fn, 'B' if bold else '', 9)
        pdf.cell(45, 6, pdf_text(label), border=0)
        pdf.set_font(fn, '', 9)
        pdf.multi_cell(0, 6, pdf_text(value), new_x='LMARGIN', new_y='NEXT')

    for idx, r in enumerate(records):
        if idx > 0:
            pdf.ln(4)
            if pdf.get_y() > 240:
                pdf.add_page()
        fn = 'AppFont' if unicode_font else 'Helvetica'
        # Заголовок записи
        pdf.set_fill_color(44, 62, 80)
        pdf.set_text_color(255)
        pdf.set_font(fn, 'B', 11)
        pdf.cell(0, 9, pdf_text(f'{r.number}  ·  {r.name}'), fill=True,
                 new_x='LMARGIN', new_y='NEXT')
        pdf.set_text_color(51)
        pdf.ln(2)

        field_row(_('Date'), r.date.strftime('%d.%m.%Y') if r.date else '')
        field_row(_('Serial'), r.serial)
        field_row(_('Machine'), r.machine.name if r.machine else '')
        field_row(_('Reason'), r.reason)
        field_row(_('Next Maintenance Date'), r.next_date.strftime('%d.%m.%Y') if r.next_date else '')
        field_row(_('Periodicity'), r.periodicity)
        field_row(_('Status'), r.status)
        field_row(_('Notes'), r.notes)
        if r.creator:
            field_row(_('Created by'), r.creator.display_name or r.creator.username)

        if r.parts:
            pdf.ln(1)
            pdf.set_font(fn, 'B', 9)
            pdf.cell(0, 6, pdf_text(_('Used Parts')), new_x='LMARGIN', new_y='NEXT')
            pdf.set_font(fn, 'B', 8)
            pdf.set_fill_color(236, 240, 241)
            pdf.cell(80, 6, pdf_text(_('Part')), border=1, fill=True)
            pdf.cell(35, 6, pdf_text('SPN'), border=1, fill=True)
            pdf.cell(25, 6, pdf_text(_('Qty')), border=1, fill=True)
            pdf.ln()
            pdf.set_font(fn, '', 8)
            for p in r.parts:
                pdf.cell(80, 6, pdf_text(p.name), border=1)
                pdf.cell(35, 6, pdf_text(p.number or ''), border=1)
                pdf.cell(25, 6, pdf_text(p.quantity), border=1)
                pdf.ln()

        if r.components:
            pdf.ln(1)
            pdf.set_font(fn, 'B', 9)
            pdf.cell(0, 6, pdf_text(_('Components')), new_x='LMARGIN', new_y='NEXT')
            pdf.set_font(fn, 'B', 8)
            pdf.set_fill_color(236, 240, 241)
            pdf.cell(40, 6, pdf_text(_('Type')), border=1, fill=True)
            pdf.cell(45, 6, pdf_text(_('Model')), border=1, fill=True)
            pdf.cell(30, 6, pdf_text(_('Size (mm)')), border=1, fill=True)
            pdf.cell(30, 6, pdf_text(_('Length')), border=1, fill=True)
            pdf.cell(20, 6, pdf_text(_('Qty')), border=1, fill=True)
            pdf.ln()
            pdf.set_font(fn, '', 8)
            for c in r.components:
                pdf.cell(40, 6, pdf_text(c.component_type or ''), border=1)
                pdf.cell(45, 6, pdf_text(c.model or ''), border=1)
                pdf.cell(30, 6, pdf_text(c.size or ''), border=1)
                pdf.cell(30, 6, pdf_text(c.length or ''), border=1)
                pdf.cell(20, 6, pdf_text(c.quantity), border=1)
                pdf.ln()

        if r.photos:
            pdf.ln(1)
            pdf.set_font(fn, 'B', 9)
            pdf.cell(0, 6, pdf_text(f'{_("Photos")} ({len(r.photos)})'),
                     new_x='LMARGIN', new_y='NEXT')
            y0 = pdf.get_y()
            x0 = pdf.l_margin
            for i, ph in enumerate(r.photos):
                if i > 0 and i % 4 == 0:
                    y0 += 32
                    x0 = pdf.l_margin
                    if y0 > 250:
                        pdf.add_page()
                        y0 = pdf.get_y()
                img_path = os.path.join(current_app.config['UPLOAD_FOLDER'], ph.filename)
                try:
                    pdf.image(img_path, x=x0 + (i % 4) * 40, y=y0, w=36, h=28)
                except Exception:
                    pass
            pdf.set_y(y0 + 32)

        # Подпись
        pdf.ln(6)
        pdf.set_font(fn, '', 8)
        pdf.set_text_color(120)
        pdf.cell(90, 8, pdf_text(f'{_("Performed by")}: ______________________'), border=0)
        pdf.cell(0, 8, pdf_text(f'{_("Signature")}: ______________________'), border=0)
        pdf.set_text_color(51)
        pdf.ln(10)

    buf = io.BytesIO()
    pdf.output(buf)
    buf.seek(0)
    return send_file(buf, mimetype='application/pdf',
                     download_name=f'mro_report_{datetime.now().strftime("%Y%m%d")}.pdf',
                     as_attachment=True)


MRO_EXPORT_FIELDS = {
    'id':          lambda r: r.id,
    'number':      lambda r: r.number or '',
    'name':        lambda r: r.name or '',
    'serial':      lambda r: r.serial or '',
    'machine':     lambda r: r.machine.name if r.machine else '',
    'date':        lambda r: r.date.strftime('%d-%m-%Y') if r.date else '',
    'reason':      lambda r: r.reason or '',
    'next_date':   lambda r: r.next_date.strftime('%d-%m-%Y') if r.next_date else '',
    'periodicity': lambda r: r.periodicity or '',
    'status':      lambda r: r.status or '',
    'notes':       lambda r: r.notes or '',
    'parts_count': lambda r: len(r.parts) if r.parts else 0,
}

MRO_EXPORT_FIELD_LABELS = {
    'id': 'ID', 'number': 'Number', 'name': 'Name', 'model_name': 'Model', 'serial': 'Serial',
    'machine': 'Machine', 'date': 'Date', 'reason': 'Reason',
    'next_date': 'Next Date', 'periodicity': 'Periodicity', 'status': 'Status',
    'notes': 'Notes', 'parts_count': 'Parts',
}

MRO_EXPORT_ALL_FIELDS = ['number', 'date', 'name', 'model_name', 'serial', 'machine', 'reason',
                          'next_date', 'periodicity', 'status']


@bp.route('/equipment/export-table/<format_type>')
@login_required
@role_required('admin', 'director', 'technician')
def equipment_export_table(format_type):
    records = _equipment_ids_query(request.args.get('ids', '')).order_by(
        EquipmentMaintenance.date.desc(), EquipmentMaintenance.id.desc()).all()

    fields_raw = request.args.get('fields', '')
    field_keys = [f.strip() for f in fields_raw.split(',') if f.strip() in MRO_EXPORT_FIELDS] if fields_raw else MRO_EXPORT_ALL_FIELDS
    if not field_keys:
        field_keys = MRO_EXPORT_ALL_FIELDS

    header_map = {k: _(MRO_EXPORT_FIELD_LABELS[k]) for k in MRO_EXPORT_FIELDS}
    headers = [header_map[k] for k in field_keys]
    rows = []
    for r in records:
        rows.append([str(MRO_EXPORT_FIELDS[k](r)) for k in field_keys])

    if format_type == 'xlsx':
        try:
            from openpyxl import Workbook
            wb = Workbook()
            ws = wb.active
            ws.title = 'MRO'
            ws.append(headers)
            for row in rows:
                ws.append(row)
            buf = io.BytesIO()
            wb.save(buf)
            buf.seek(0)
            return send_file(buf, mimetype='application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
                             download_name=f'mro_{datetime.now().strftime("%Y%m%d")}.xlsx', as_attachment=True)
        except ImportError:
            flash(_('Excel export is temporarily unavailable'), 'error')
            return redirect(url_for('equipment.equipment_list'))
    elif format_type == 'csv':
        buf = io.StringIO()
        writer = csv.writer(buf)
        writer.writerow(headers)
        writer.writerows(rows)
        buf.seek(0)
        return send_file(io.BytesIO(buf.getvalue().encode('utf-8-sig')), mimetype='text/csv',
                         download_name=f'mro_{datetime.now().strftime("%Y%m%d")}.csv', as_attachment=True)
    elif format_type == 'pdf':
        try:
            fpdf_mod = ensure_fpdf()
            FPDF = fpdf_mod.FPDF
        except Exception:
            flash(_('PDF export is temporarily unavailable'), 'error')
            return redirect(url_for('equipment.equipment_list'))
        date_str = datetime.now().strftime('%d-%m-%Y %H:%M')
        title = _('Mule Maintenance')
        subtitle = f'{date_str} - {len(records)} {_("records")}'
        footer_txt = _('Generated by ProMaster CRM')
        page_txt = _('page')
        font_path = find_pdf_font()
        unicode_font = bool(font_path)

        def pdf_text(s):
            s = str(s if s is not None else '')
            return s if unicode_font else s.encode('latin-1', 'replace').decode('latin-1')

        try:
            class MroTablePDF(FPDF):
                def header(self):
                    fn = 'AppFont' if unicode_font else 'Helvetica'
                    self.set_font(fn, 'B', 12)
                    self.cell(0, 8, pdf_text(f'{title} - ProMaster'), new_x='LMARGIN', new_y='NEXT')
                    self.set_font(fn, '', 8)
                    self.cell(0, 5, pdf_text(subtitle), new_x='LMARGIN', new_y='NEXT')
                    self.ln(2)
                def footer(self):
                    fn = 'AppFont' if unicode_font else 'Helvetica'
                    self.set_y(-12)
                    self.set_font(fn, '', 7)
                    self.set_text_color(128)
                    self.cell(0, 8, pdf_text(f'{footer_txt} - {page_txt} {self.page_no()}/{{nb}}'), align='C')

            pdf = MroTablePDF(orientation='L', unit='mm', format='A4')
            pdf.alias_nb_pages()
            pdf.set_auto_page_break(auto=True, margin=15)
            if unicode_font:
                try:
                    pdf.add_font('AppFont', '', font_path)
                    pdf.add_font('AppFont', 'B', font_path)
                    base_font = 'AppFont'
                except Exception:
                    unicode_font = False
                    base_font = 'Helvetica'
            else:
                base_font = 'Helvetica'
            pdf.add_page()
            n_cols = len(headers)
            col_w = [277 / n_cols] * n_cols
            pdf.set_font(base_font, 'B', 7)
            pdf.set_fill_color(44, 62, 80)
            pdf.set_text_color(255)
            for i, h in enumerate(headers):
                pdf.cell(col_w[i], 7, pdf_text(h), border=1, fill=True)
            pdf.ln()
            pdf.set_font(base_font, '', 6.5)
            pdf.set_text_color(51)
            for idx, row in enumerate(rows):
                fill = (idx % 2 == 1)
                if fill:
                    pdf.set_fill_color(249, 249, 249)
                for i, val in enumerate(row):
                    pdf.cell(col_w[i], 6, pdf_text(val), border=1, fill=fill)
                pdf.ln()
            buf = io.BytesIO()
            pdf.output(buf)
            buf.seek(0)
            return send_file(buf, mimetype='application/pdf',
                             download_name=f'mro_{datetime.now().strftime("%Y%m%d")}.pdf', as_attachment=True)
        except Exception as e:
            flash(_('PDF export failed: %(err)s', err=str(e)), 'error')
            return redirect(url_for('equipment.equipment_list'))
    flash(_('Unsupported format'), 'error')
    return redirect(url_for('equipment.equipment_list'))
